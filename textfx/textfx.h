/*
 * Character-cell text effects for the boot display (openspec change
 * the-boot-plays-terminal-text-effects).
 *
 * One portable implementation for U-Boot stage 1 and early Linux: a cell grid,
 * the TFXS cell-sequence container written by tools/textfx_frames.py, an ANSI
 * frame parser for the live `ttfx --parity-dump` stream, and a glyph blitter
 * (8x16 Unifont glyphs, integer scale) into XRGB8888 or RGB565.
 *
 * Freestanding: only <stdint.h>, <stddef.h>.  No malloc, no floating point, no
 * libc calls.  Multi-byte values are read and written byte by byte
 * little-endian.  The caller owns every buffer.
 */
#ifndef TEXTFX_H
#define TEXTFX_H

#include <stddef.h>
#include <stdint.h>

#define TFX_GLYPH_W 8u
#define TFX_GLYPH_H 16u
#define TFX_MAX_CELLS 2048u
#define TFX_FNV_INIT 0x811c9dc5u

struct tfx_cell {
	uint16_t cp; /* code point; blank is 0x20 with colour 0 */
	uint8_t r, g, b;
};

struct tfx_grid {
	unsigned cols, rows;
	struct tfx_cell cells[TFX_MAX_CELLS];
};

/* Fill with blanks.  -1 if cols*rows is 0 or exceeds TFX_MAX_CELLS. */
int tfx_grid_init(struct tfx_grid *g, unsigned cols, unsigned rows);

uint32_t tfx_fnv1a(const void *data, size_t len, uint32_t h);
/* FNV-1a 32 over, for each cell in index order: cp low, cp high, r, g, b. */
uint32_t tfx_grid_hash(const struct tfx_grid *g);

/* ---- TFXS sequence (see tools/textfx_frames.py for the layout) ---- */
#define TFX_SEQ_HEADER 32u

struct tfx_seq {
	const uint8_t *payload;
	size_t payload_len, pos;
	unsigned cols, rows, fps, nframes, frame; /* frame = frames consumed */
	uint32_t seed, digest;
};

/* 0 if the header and payload checksum are valid, else -1. */
int tfx_seq_open(struct tfx_seq *s, const uint8_t *buf, size_t len);
void tfx_seq_rewind(struct tfx_seq *s);
/*
 * Apply the next frame to g (which must have the sequence's dimensions and
 * hold the previous frame).  Writes the indices of changed cells to changed[]
 * (capacity cap) and returns their count, or -1 at the end or on a malformed
 * frame.  A frame with more changes than cap is a malformed frame.
 */
int tfx_seq_next(struct tfx_seq *s, struct tfx_grid *g, uint16_t *changed, size_t cap);

/* ---- live ttfx --parity-dump frames ---- */
/*
 * Parse one frame's bytes (UTF-8, rows joined by '\n', SGR 0 and 38;2;r;g;b
 * only) into g, which must already have the right dimensions.  Records the
 * indices of cells that differ from g's previous content in changed[]/cap and
 * returns their count; -1 on any unsupported byte, escape, wide or non-BMP
 * character, or a row/column count that does not match.  g is unchanged on -1.
 */
int tfx_parse_frame(struct tfx_grid *g, const uint8_t *buf, size_t len,
		    uint16_t *changed, size_t cap);

/* ---- drawing ---- */
enum tfx_fmt { TFX_XRGB8888 = 0, TFX_RGB565 = 1 };

/*
 * Orientation of the picture on the native scanout.  TFX_ROT_NONE draws the
 * picture as is (portrait panel).  TFX_ROT_LANDSCAPE draws a landscape picture
 * the way the shell's Sway `transform 270` shows one: logical pixel (lx, ly) of a
 * W x H picture lands at native pixel (ly, W - 1 - lx) of an H x W buffer.  That is
 * the mapping the repo's landscape touch calibration records (logical (x, y) is
 * panel (y, 1232 - x), docs/evidence/panel-landscape/README.md).
 */
enum tfx_rot { TFX_ROT_NONE = 0, TFX_ROT_LANDSCAPE = 1 };

struct tfx_surface {
	void *pixels;           /* the NATIVE buffer */
	size_t stride_bytes;    /* of the native buffer */
	unsigned width, height; /* LOGICAL picture size in pixels (1232x568 when landscape) */
	enum tfx_fmt fmt;
	unsigned scale;  /* glyph pixel is scale x scale device pixels, >= 1 */
	unsigned x0, y0; /* top-left of cell (0,0) in the logical picture */
	enum tfx_rot rot;
};

/* Draw one cell over a black background; cells outside the surface are clipped. */
void tfx_draw_cell(const struct tfx_grid *g, unsigned idx, const struct tfx_surface *s);
void tfx_draw_all(const struct tfx_grid *g, const struct tfx_surface *s);
/* Clear the whole surface to black. */
void tfx_clear(const struct tfx_surface *s);
/* FNV-1a over the native buffer row by row (native width * bytes-per-pixel each). */
uint32_t tfx_surface_hash(const struct tfx_surface *s);

/* 1 if the font has a glyph for cp, else 0 (the fallback box is drawn). */
int tfx_has_glyph(uint16_t cp);

/* Generated by tools/gen-textfx-font.py. */
extern const unsigned tfx_font_count;
extern const uint16_t tfx_font_cp[];
extern const uint8_t tfx_font_bits[][16];

#endif
