#!/usr/bin/env python3
"""Generate the keyboard base's TCA8418 linux,keymap (keyboard-base task 3.1).

The table is LILYGO's tca8418_key_name() (ui_hardware.c, tree 4a87c53c):
vendor code -> printed legend. A vendor code is the TCA8418 key event value
(1-based), so row = (code - 1) // 10 and column = (code - 1) % 10, the same
split the kernel's tca8418_keypad driver makes before looking up the keymap.
Codes 4, 30 and 31 have no legend in the vendor table and stay unmapped.

  tools/keyboard-base-keymap.py            print the keymap block
  tools/keyboard-base-keymap.py --check F  exit 1 unless F holds it verbatim
"""
import argparse
import sys

ROWS, COLS = 7, 10
BEGIN = "\t\t\t// BEGIN generated by tools/keyboard-base-keymap.py"
END = "\t\t\t// END generated by tools/keyboard-base-keymap.py"

# code: (legend, Linux key code name)
KEYS = {
    1: ("RIGHT", "KEY_RIGHT"), 2: ("LEFT", "KEY_LEFT"),
    3: ("FN-R", "KEY_RIGHTALT"), 5: ("SPACE", "KEY_SPACE"),
    6: ("TAB", "KEY_TAB"), 7: ("SHIFT", "KEY_LEFTSHIFT"),
    8: ("LILYGO", "KEY_LEFTMETA"), 9: ("FN", "KEY_RIGHTALT"),
    10: ("CAPS", "KEY_CAPSLOCK"), 11: ("MIC", "KEY_MICMUTE"),
    12: ("DOWN", "KEY_DOWN"), 13: ("M", "KEY_M"), 14: ("SPACE", "KEY_SPACE"),
    15: ("V", "KEY_V"), 16: ("C", "KEY_C"), 17: ("X", "KEY_X"),
    18: ("Z", "KEY_Z"), 19: ("ALT", "KEY_LEFTALT"), 20: ("Q", "KEY_Q"),
    21: ("ENTER", "KEY_ENTER"), 22: ("UP", "KEY_UP"),
    23: ("CTRL", "KEY_LEFTCTRL"), 24: ("N", "KEY_N"), 25: ("B", "KEY_B"),
    26: ("F", "KEY_F"), 27: ("D", "KEY_D"), 28: ("S", "KEY_S"),
    29: ("A", "KEY_A"), 32: ("L", "KEY_L"), 33: ("K", "KEY_K"),
    34: ("J", "KEY_J"), 35: ("H", "KEY_H"), 36: ("G", "KEY_G"),
    37: ("R", "KEY_R"), 38: ("E", "KEY_E"), 39: ("W", "KEY_W"),
    40: ("ESC", "KEY_ESC"),
    # LILYGO's own UI turns DEL into LV_KEY_BACKSPACE.
    41: ("DEL", "KEY_BACKSPACE"),
    42: ("P", "KEY_P"), 43: ("O", "KEY_O"), 44: ("I", "KEY_I"),
    45: ("U", "KEY_U"), 46: ("Y", "KEY_Y"), 47: ("T", "KEY_T"),
    48: ("2", "KEY_2"), 49: ("1", "KEY_1"), 50: ("F1", "KEY_F1"),
    51: ("0", "KEY_0"), 52: ("9", "KEY_9"), 53: ("8", "KEY_8"),
    54: ("7", "KEY_7"), 55: ("6", "KEY_6"), 56: ("5", "KEY_5"),
    57: ("4", "KEY_4"), 58: ("3", "KEY_3"), 59: ("F3", "KEY_F3"),
    60: ("F2", "KEY_F2"), 61: ("F11", "KEY_F11"), 62: ("F10", "KEY_F10"),
    63: ("F9", "KEY_F9"), 64: ("F8", "KEY_F8"), 65: ("F7", "KEY_F7"),
    66: ("F6", "KEY_F6"), 67: ("F5", "KEY_F5"), 68: ("F4", "KEY_F4"),
}


def position(code):
    return (code - 1) // COLS, (code - 1) % COLS


def code_at(row, col):
    return row * COLS + col + 1


def block():
    lines = [BEGIN, "\t\t\tlinux,keymap ="]
    entries = []
    for code in sorted(KEYS):
        row, col = position(code)
        legend, key = KEYS[code]
        entries.append(f"\t\t\t\t<MATRIX_KEY({row}, {col}, {key})>\t/* {code:2d} {legend} */")
    for i, e in enumerate(entries):
        body, comment = e.split("\t/*")
        lines.append(body + ("," if i < len(entries) - 1 else ";") + "\t/*" + comment)
    lines.append(END)
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", metavar="FILE")
    args = ap.parse_args()
    if args.check:
        text = open(args.check).read()
        if block() not in text:
            print(f"{args.check}: keymap block is stale; regenerate it", file=sys.stderr)
            return 1
        return 0
    sys.stdout.write(block())
    return 0


if __name__ == "__main__":
    sys.exit(main())
