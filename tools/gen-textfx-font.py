#!/usr/bin/env python3
"""Generate textfx/textfx_font.c from GNU Unifont's BDF (8x16 glyphs only).

  python3 -I tools/gen-textfx-font.py --bdf <unifont.bdf> --out textfx/textfx_font.c

The code points are the ones ttfx's 37 effects draw over the K230 banner plus
printable ASCII (see docs/evidence/boot-text-effects/ttfx-research.md).
Unifont is SIL OFL 1.1 or GPL-2.0-or-later with the GNU Font Embedding
Exception; the notice is carried into the generated file.
"""
import argparse
import hashlib
import re
import sys

RANGES = [
    (0x20, 0x7E),      # printable ASCII
    (0xA1, 0xFF),      # Latin-1 Supplement
    (0x100, 0x1C3),    # Latin Extended-A and part of B (decrypt)
    (0x2022, 0x2022),  # bullet
    (0x2500, 0x259F),  # box drawing and block elements
    (0x25C9, 0x25C9), (0x25CE, 0x25CF), (0x25E6, 0x25E6),
    (0xFF66, 0xFF9F),  # half-width katakana (decrypt, matrix)
]


def parse_bdf(text):
    glyphs = {}
    for m in re.finditer(r"STARTCHAR [^\n]*\nENCODING (\d+)\n(.*?)ENDCHAR", text, re.S):
        cp = int(m.group(1))
        body = m.group(2)
        bbx = re.search(r"BBX (\d+) (\d+) (-?\d+) (-?\d+)", body)
        parts = re.split(r"BITMAP[ \t]*\r?\n", body, maxsplit=1)
        if bbx is None or len(parts) != 2:
            continue
        w, h, xo, yo = (int(v) for v in bbx.groups())
        rows = parts[1].split()
        glyphs[cp] = (w, h, xo, yo, rows)
    return glyphs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bdf", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    raw = open(a.bdf, "rb").read()
    text = raw.decode("utf-8")
    version = re.search(r'FONT_VERSION "([^"]+)"', text).group(1)
    glyphs = parse_bdf(text)
    cps, bitmaps, missing = [], [], []
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            g = glyphs.get(cp)
            if g is None:
                missing.append(cp)
                continue
            w, h, xo, yo, rows = g
            if (w, h, xo, yo) != (8, 16, 0, -2) or len(rows) != 16:
                missing.append(cp)  # not an 8x16 glyph: the renderer draws its fallback
                continue
            cps.append(cp)
            bitmaps.append([int(r, 16) for r in rows])
    out = []
    out.append("/* GENERATED by tools/gen-textfx-font.py; do not edit.\n"
               f" * Source: GNU Unifont {version} BDF, sha256 {hashlib.sha256(raw).hexdigest()}.\n"
               " * Glyph set: printable ASCII, Latin-1, Latin Extended-A/B subset, box drawing,\n"
               " * block elements, a few geometric shapes and half-width katakana (8x16 only).\n"
               " * Unifont is Copyright (C) 1998-2026 Roman Czyborra, Paul Hardy, Qianqian Fang,\n"
               " * Andrew Miller, Johnnie Weaver, David Corbett, et al., licensed under the SIL\n"
               " * Open Font License 1.1 and the GNU GPL version 2 or later with the GNU Font\n"
               " * Embedding Exception.\n"
               f" * {len(cps)} glyphs; {len(missing)} requested code points have no 8x16 glyph.\n */\n")
    out.append('#include "textfx.h"\n\n')
    out.append(f"const unsigned tfx_font_count = {len(cps)}u;\n\n")
    out.append("const uint16_t tfx_font_cp[] = {")
    for i, cp in enumerate(cps):
        out.append(("\n\t" if i % 12 == 0 else " ") + f"0x{cp:04x},")
    out.append("\n};\n\n")
    out.append("const uint8_t tfx_font_bits[][16] = {\n")
    for bm in bitmaps:
        out.append("\t{ " + ", ".join(f"0x{b:02x}" for b in bm) + " },\n")
    out.append("};\n")
    open(a.out, "w").write("".join(out))
    print(f"{len(cps)} glyphs, {len(missing)} without an 8x16 glyph", file=sys.stderr)


if __name__ == "__main__":
    main()
