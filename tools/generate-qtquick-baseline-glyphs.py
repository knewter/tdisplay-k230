#!/usr/bin/env python3
"""Regenerate nix/qtquick-shm-baseline/glyphs.h.

The SHM baseline has no font stack; it embeds 8-bit coverage bitmaps for exactly
the strings the Qt Quick probe draws (plus the characters a person may type in
the edit field) at the probe's four pixel sizes. DejaVu Sans is the board's
fontconfig default `sans`, so the Qt probe resolves to the same face.

usage: generate-qtquick-baseline-glyphs.py DEJAVU_SANS_TTF
"""
from pathlib import Path
import sys

from PIL import Image, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "nix/qtquick-shm-baseline/glyphs.h"
SIZES = {
    19: "Tap / retarget" + "ShaderEffect negative control below"
        + "Software-safe solid rectangle",
    24: "Scroll row 0123456789",
    27: "Tap to edit" + "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"
        + "0123456789 .,-_/",
    30: "Qt Quick software probe",
}


def main():
    font_path = sys.argv[1]
    lines = [
        "/* Generated by tools/generate-qtquick-baseline-glyphs.py; do not edit. */",
        "struct glyph { int size; unsigned ch; int w, h, ox, oy, adv; unsigned off; };",
    ]
    data = []
    table = []
    tile = Image.open(ROOT / "nix/qtquick-software-probe/tile.png").convert("RGBA")
    for size, chars in sorted(SIZES.items()):
        font = ImageFont.truetype(font_path, size)
        ascent, _ = font.getmetrics()
        for ch in sorted(set(chars)):
            adv = round(font.getlength(ch))
            if ch == " ":
                table.append((size, ord(ch), 0, 0, 0, 0, adv, len(data)))
                continue
            left, top, right, bottom = font.getbbox(ch)
            w, h = right - left, bottom - top
            mask = Image.new("L", (max(w, 1), max(h, 1)), 0)
            from PIL import ImageDraw
            ImageDraw.Draw(mask).text((-left, -top), ch, font=font, fill=255)
            off = len(data)
            data.extend(mask.tobytes())
            table.append((size, ord(ch), w, h, left, top - ascent, adv, off))
    lines.append("static const unsigned char glyph_data[] = {")
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("  0};")
    lines.append("static const struct glyph glyphs[] = {")
    for row in table:
        lines.append("  {%d,%d,%d,%d,%d,%d,%d,%d}," % row)
    lines.append("};")
    lines.append("static const unsigned char tile_rgba[] = {")
    raw = tile.tobytes()
    for i in range(0, len(raw), 24):
        lines.append("  " + ",".join(str(b) for b in raw[i:i + 24]) + ",")
    lines.append("  0};")
    lines.append("#define TILE_SIZE %d" % tile.width)
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT, len(table), "glyphs", len(data), "bytes")


main()
